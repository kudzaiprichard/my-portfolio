// lib/audioEngine.ts
/**
 * One Web Audio engine for every sound on the page.
 *
 *   key clips (decoded once) ─ BufferSource (detune) ─ Gain ─ StereoPanner ─┐
 *   UI sounds (synthesised) ──────────────────────────────────────────────── SFX bus ─┐
 *                                                                 Compressor ─ Master gain ─ speakers
 *
 * Why Web Audio rather than <audio> elements: volume works on iOS (where
 * HTMLMediaElement.volume is read-only), detune changes pitch for real
 * (playbackRate on <audio> preserves pitch), sounds start with low and steady
 * latency, and mute is one gain ramp. The context is created inside the
 * first user gesture, which iOS requires.
 */

const MUTE_KEY = 'keystroke-audio-muted'
const MUTE_EVENT = 'audio-mute-change'

/**
 * The keystroke clips, by name. Their audio is embedded (lib/keystrokeClips,
 * generated by scripts/embed-sounds.mjs) rather than served as .mp3 files:
 * download-manager tools pop up a "download this audio" button for every
 * audio file a page requests.
 */
export const KEY_CLIPS = ['keystroke_1', 'keystroke_2', 'keystroke_3', 'keystroke_4'] as const

/**
 * Each recording holds a key going down and, about 100 ms later, coming back
 * up. Where the two sit in each clip (seconds), measured from the envelopes of
 * assets/sounds/*.mp3, so they can be played separately with a human gap.
 */
const KEY_CLIP_PARTS: Record<string, Record<'press' | 'release', [number, number]>> = {
    keystroke_1: { press: [0.008, 0.105], release: [0.108, 0.169] },
    keystroke_2: { press: [0.007, 0.1], release: [0.103, 0.217] },
    keystroke_3: { press: [0.022, 0.125], release: [0.128, 0.193] },
    keystroke_4: { press: [0, 0.1], release: [0.104, 0.265] },
}

/** The embedded clips as bytes, loaded in their own small chunk. */
function loadClipBytes(): Promise<ArrayBuffer[]> {
    return import('@/src/lib/keystrokeClips').then(({ KEYSTROKE_CLIPS_BASE64 }) =>
        KEYSTROKE_CLIPS_BASE64.map(b64 => {
            const bin = atob(b64)
            const bytes = new Uint8Array(bin.length)
            for (let i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i)
            return bytes.buffer
        }))
}

/** Interface sounds. Each has one meaning; levels sit within a few dB of each other. */
type UiSound = 'success' | 'error' | 'boot' | 'achievement' | 'load' | 'loaded' | 'blip' | 'gameover'

interface ClipOptions {
    gain: number
    /** Cents */
    detune?: number
    /** −1 (left) … 1 (right) */
    pan?: number
    /** Only the key-down or key-up half of the recording (whole clip when omitted) */
    part?: 'press' | 'release'
    /** Start this much later (ms) */
    delayMs?: number
    /** Low-pass cutoff (Hz) for the stroke's tone; 0 = none */
    lowpass?: number
}

class AudioEngine {
    private ctx: AudioContext | null = null
    private master: GainNode | null = null
    private sfx: GainNode | null = null
    private buffers = new Map<string, AudioBuffer>()
    private loading: Promise<void> | null = null
    // The clips' bytes, fetched at install so decoding at unlock is instant
    private clipBytes: Promise<ArrayBuffer[]> | null = null

    private muted = false
    // Told when audio unlocks or the mute / plain-mode state changes
    private listeners = new Set<() => void>()
    // Plain mode: no sound at all, whatever the mute setting
    private suppressed = false
    private installed = false

    // agent "thinking" ticks
    private thinkTimer: ReturnType<typeof setInterval> | null = null

    // microphone meter (agent orb while listening)
    private micStream: MediaStream | null = null
    private micAnalyser: AnalyserNode | null = null
    private micData: Uint8Array<ArrayBuffer> | null = null
    private micWanted = false

    // ============================================
    // Setup
    // ============================================

    /** Listen for the first gesture (to unlock audio) and for mute changes. Idempotent. */
    install(): void {
        if (this.installed || typeof window === 'undefined') return
        this.installed = true
        // Load the keystroke clips now (no AudioContext needed yet), so the
        // first section has its sounds the moment audio is unlocked
        this.clipBytes = loadClipBytes()
        this.clipBytes.catch(() => { /* retried at unlock */ })
        try { this.muted = localStorage.getItem(MUTE_KEY) === 'true' } catch { /* storage blocked */ }

        const unlock = () => {
            this.unlock()
            window.removeEventListener('pointerdown', unlock, true)
            window.removeEventListener('keydown', unlock, true)
            window.removeEventListener('touchstart', unlock, true)
        }
        window.addEventListener('pointerdown', unlock, true)
        window.addEventListener('keydown', unlock, true)
        window.addEventListener('touchstart', unlock, true)

        window.addEventListener(MUTE_EVENT, (e: Event) => {
            this.setMuted(!!(e as CustomEvent<{ muted: boolean }>).detail?.muted)
        })
        // Another tab toggled mute
        window.addEventListener('storage', (e: StorageEvent) => {
            if (e.key === MUTE_KEY) this.setMuted(e.newValue === 'true')
        })
    }

    /** Create/resume the context. Must run inside a user gesture the first time. */
    unlock(): void {
        if (typeof window === 'undefined') return
        if (!this.ctx) {
            const Ctor = window.AudioContext ?? (window as unknown as { webkitAudioContext?: typeof AudioContext }).webkitAudioContext
            if (!Ctor) return
            const ctx = new Ctor()
            const compressor = ctx.createDynamicsCompressor()
            compressor.threshold.value = -18
            compressor.ratio.value = 4
            const master = ctx.createGain()
            master.gain.value = this.muted || this.suppressed ? 0 : 1
            const sfx = ctx.createGain()
            sfx.connect(compressor)
            compressor.connect(master)
            master.connect(ctx.destination)

            Object.assign(this, { ctx, master, sfx })
            void this.loadClips()
        }
        if (this.ctx?.state === 'suspended') void this.ctx.resume()
        this.notify()
    }

    private notify(): void {
        this.listeners.forEach(fn => fn())
    }

    /** Subscribe to unlock / mute / plain-mode changes (for useSyncExternalStore). */
    subscribe = (fn: () => void): (() => void) => {
        this.listeners.add(fn)
        return () => { this.listeners.delete(fn) }
    }

    /**
     * Sound would be heard but the browser hasn't allowed it yet: no click or
     * key press on this page so far (e.g. after a refresh), audio is not muted
     * and Web Audio exists. Sections wait for that first gesture so their
     * typing is heard (sectionStart.waitForSound in typingConfig).
     */
    waitingForGesture = (): boolean => {
        if (typeof window === 'undefined' || this.ctx || this.suppressed) return false
        if (!(window.AudioContext ?? (window as unknown as { webkitAudioContext?: unknown }).webkitAudioContext)) return false
        let muted = this.muted
        if (!this.installed) {
            try { muted = localStorage.getItem(MUTE_KEY) === 'true' } catch { /* storage blocked */ }
        }
        return !muted
    }

    private loadClips(): Promise<void> {
        const ctx = this.ctx
        if (!ctx) return Promise.resolve()
        const bytes = (this.clipBytes ?? Promise.reject())
            .catch(() => loadClipBytes())
        this.loading ??= bytes.then(all => Promise.all(all.map(async (buf, i) => {
            // decodeAudioData detaches its buffer: decode a copy
            this.buffers.set(KEY_CLIPS[i], await ctx.decodeAudioData(buf.slice(0)))
        }))).then(() => undefined, () => undefined)
        return this.loading
    }

    /** Unlocked and not muted. (A context still resuming plays what was scheduled once it runs.) */
    get ready(): boolean {
        return !!this.ctx && this.ctx.state !== 'closed' && !this.muted && !this.suppressed
    }

    /** Plain mode: silence every sound until lifted. */
    setSuppressed(on: boolean): void {
        this.suppressed = on
        const { ctx, master } = this
        if (ctx && master) master.gain.setTargetAtTime(on || this.muted ? 0 : 1, ctx.currentTime, 0.02)
        this.notify()
    }

    // ============================================
    // Mute
    // ============================================

    setMuted(muted: boolean): void {
        this.muted = muted
        const { ctx, master } = this
        if (ctx && master) master.gain.setTargetAtTime(muted || this.suppressed ? 0 : 1, ctx.currentTime, 0.02) // ≈60 ms ramp
        this.notify()
    }

    // ============================================
    // Keystrokes
    // ============================================

    /** Play a decoded clip. Silently does nothing until unlocked and loaded. */
    playClip(url: string, { gain, detune = 0, pan = 0, part, delayMs = 0, lowpass = 0 }: ClipOptions): void {
        const { ctx, sfx } = this
        const buffer = this.buffers.get(url)
        if (!ctx || !sfx || !buffer || !this.ready) return
        const t = ctx.currentTime + delayMs / 1000
        const span = part ? KEY_CLIP_PARTS[url]?.[part] : undefined
        const offset = span ? span[0] : 0
        const duration = (span ? Math.min(span[1], buffer.duration) : buffer.duration) - offset
        const src = ctx.createBufferSource()
        src.buffer = buffer
        src.detune.value = detune
        const g = new GainNode(ctx, { gain })
        // A part ends mid-recording: fade its last few ms so the cut never clicks
        if (span) {
            g.gain.setValueAtTime(gain, t + Math.max(0, duration - 0.006))
            g.gain.linearRampToValueAtTime(0, t + duration)
        }
        const p = new StereoPannerNode(ctx, { pan })
        const tone = lowpass ? src.connect(new BiquadFilterNode(ctx, { type: 'lowpass', frequency: lowpass, Q: 0.5 })) : src
        tone.connect(g).connect(p).connect(sfx)
        src.start(t, offset, duration)
    }

    /** A pressed keycap button: the Enter keystroke, centred. */
    keycap(): void {
        this.playClip(KEY_CLIPS[1], { gain: 0.35, detune: (Math.random() * 2 - 1) * 30 })
    }

    // ============================================
    // Interface sounds (synthesised)
    // ============================================

    private tone(freqs: number[], { type = 'sine' as OscillatorType, dur = 0.14, gain = 0.1, gap = 0.08, lowpass = 0 } = {}): void {
        const { ctx, sfx } = this
        if (!ctx || !sfx || !this.ready) return
        freqs.forEach((f, i) => {
            const t = ctx.currentTime + i * gap
            const osc = new OscillatorNode(ctx, { type, frequency: f })
            const g = new GainNode(ctx, { gain: 0.0001 })
            g.gain.setValueAtTime(0.0001, t)
            g.gain.exponentialRampToValueAtTime(gain, t + 0.01)
            g.gain.exponentialRampToValueAtTime(0.0001, t + dur)
            let node: AudioNode = osc
            if (lowpass) node = osc.connect(new BiquadFilterNode(ctx, { type: 'lowpass', frequency: lowpass }))
            node.connect(g).connect(sfx)
            osc.start(t)
            osc.stop(t + dur + 0.05)
        })
    }

    /**
     * A soft tone that glides between two pitches, with a slow attack and a
     * long, gentle release: smooth, never a click or a buzz.
     */
    private glide(from: number, to: number, { type = 'sine' as OscillatorType, dur = 0.4, gain = 0.05, attack = 0.05, delay = 0, lowpass = 1800 } = {}): void {
        const { ctx, sfx } = this
        if (!ctx || !sfx || !this.ready) return
        const t = ctx.currentTime + delay
        const osc = new OscillatorNode(ctx, { type, frequency: from })
        osc.frequency.setValueAtTime(from, t)
        osc.frequency.exponentialRampToValueAtTime(to, t + dur * 0.7)
        const g = new GainNode(ctx, { gain: 0.0001 })
        g.gain.setValueAtTime(0.0001, t)
        g.gain.exponentialRampToValueAtTime(gain, t + attack)
        g.gain.exponentialRampToValueAtTime(0.0001, t + dur)
        osc.connect(new BiquadFilterNode(ctx, { type: 'lowpass', frequency: lowpass, Q: 0.3 })).connect(g).connect(sfx)
        osc.start(t)
        osc.stop(t + dur + 0.05)
    }

    play(sound: UiSound): void {
        switch (sound) {
            case 'success': return this.tone([880, 1318.5], { dur: 0.12, gap: 0.07, gain: 0.1 })
            case 'error': return this.tone([329.63, 261.63], { type: 'triangle', dur: 0.22, gap: 0.09, gain: 0.07, lowpass: 1200 })
            case 'boot': return this.tone([523.25, 783.99, 1046.5], { dur: 0.5, gap: 0.11, gain: 0.1 })
            case 'achievement': return this.tone([659.25, 987.77, 1318.5, 1975.5], { dur: 0.35, gap: 0.09, gain: 0.09 })
            // The terminal starts fetching a section: a soft swell rising a fifth (G4 → D5), an octave shimmer above
            case 'load':
                this.glide(392, 587.33, { type: 'triangle', dur: 0.45, gain: 0.05, attack: 0.08 })
                return this.glide(784, 1174.66, { dur: 0.4, gain: 0.016, attack: 0.1, delay: 0.03, lowpass: 2600 })
            // A game point (the snake eats): one short, soft high note (C6)
            case 'blip': return this.tone([1046.5], { dur: 0.07, gain: 0.05, lowpass: 3200 })
            // Game over: a gentle fall of a fifth, never a buzzer
            case 'gameover': return this.glide(440, 293.66, { type: 'triangle', dur: 0.55, gain: 0.05, attack: 0.02 })
            // ...and it has arrived: two gentle bell notes (D5, A5) that ring out
            case 'loaded':
                this.glide(587.33, 587.33, { dur: 0.55, gain: 0.04, attack: 0.012, lowpass: 2400 })
                return this.glide(880, 880, { dur: 0.7, gain: 0.034, attack: 0.012, delay: 0.09, lowpass: 2800 })
        }
    }

    private tick(index: number): void {
        // A quiet two-note sine pulse (A5, E5), like a slow heartbeat
        this.tone([index % 2 ? 659.25 : 880], { dur: 0.09, gain: 0.035, lowpass: 2400 })
    }

    /** A soft, slow pulse while the agent is waiting on the network. */
    startThinking(): void {
        if (this.thinkTimer) return
        let i = 0
        this.tick(i++)
        this.thinkTimer = setInterval(() => this.tick(i++), 420)
    }

    stopThinking(): void {
        if (this.thinkTimer) clearInterval(this.thinkTimer)
        this.thinkTimer = null
    }

    // ============================================
    // Microphone level (agent orb while listening)
    // ============================================

    async startMicMeter(): Promise<void> {
        if (this.micWanted || typeof navigator === 'undefined' || !navigator.mediaDevices?.getUserMedia) return
        this.micWanted = true
        this.unlock()
        const ctx = this.ctx
        if (!ctx) return
        try {
            const stream = await navigator.mediaDevices.getUserMedia({ audio: true })
            // Listening may have ended while the permission prompt was open
            if (!this.micWanted) {
                stream.getTracks().forEach(t => t.stop())
                return
            }
            const analyser = new AnalyserNode(ctx, { fftSize: 256, smoothingTimeConstant: 0.6 })
            // Analysed only — never routed to the speakers
            ctx.createMediaStreamSource(stream).connect(analyser)
            this.micStream = stream
            this.micAnalyser = analyser
            this.micData = new Uint8Array(new ArrayBuffer(analyser.frequencyBinCount))
        } catch {
            // Permission denied or no mic: the orb keeps its canned animation
            this.micWanted = false
        }
    }

    stopMicMeter(): void {
        this.micWanted = false
        this.micStream?.getTracks().forEach(t => t.stop())
        this.micStream = null
        this.micAnalyser?.disconnect()
        this.micAnalyser = null
        this.micData = null
    }

    /** Current mic level, 0–1, or null when no meter is running. */
    getMicLevel(): number | null {
        const { micAnalyser, micData } = this
        if (!micAnalyser || !micData) return null
        micAnalyser.getByteTimeDomainData(micData)
        let peak = 0
        for (let i = 0; i < micData.length; i++) peak = Math.max(peak, Math.abs(micData[i] - 128))
        return Math.min(1, peak / 64)
    }
}

/** The page's single audio engine. */
export const audioEngine = new AudioEngine()

/**
 * Store the mute choice and tell every listener (the engine, the mute
 * toggle, other tabs via the storage event).
 */
export function setAudioMuted(muted: boolean): void {
    try { localStorage.setItem(MUTE_KEY, String(muted)) } catch { /* storage blocked */ }
    window.dispatchEvent(new CustomEvent(MUTE_EVENT, { detail: { muted } }))
}
