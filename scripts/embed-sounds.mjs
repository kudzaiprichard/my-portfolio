// scripts/embed-sounds.mjs
//
// Embeds the keystroke clips (assets/sounds/keystroke_*.mp3) into
// src/lib/keystrokeClips.ts as base64, so the page never requests an audio
// file: download-manager tools (e.g. Internet Download Manager) pop up a
// "download this audio" button for every .mp3 a page fetches.
//
//   node scripts/embed-sounds.mjs      (re-run after changing a clip)

import { readFileSync, writeFileSync, readdirSync } from 'node:fs'

const dir = 'assets/sounds'
const files = readdirSync(dir).filter(f => /^keystroke_\d+\.mp3$/.test(f)).sort()
if (files.length === 0) throw new Error(`No keystroke_*.mp3 in ${dir}`)

const entries = files.map(f => `    // ${f}\n    '${readFileSync(`${dir}/${f}`).toString('base64')}',`)
const out = `// lib/keystrokeClips.ts
// GENERATED by scripts/embed-sounds.mjs from assets/sounds — do not edit.
// The keystroke clips as base64 MP3, loaded with import() by the audio
// engine, so no audio file is ever requested (download managers pop up a
// "download" button for those).

export const KEYSTROKE_CLIPS_BASE64: readonly string[] = [
${entries.join('\n')}
]
`
writeFileSync('src/lib/keystrokeClips.ts', out)
console.log(`Embedded ${files.length} clips into src/lib/keystrokeClips.ts`)
